-- Scheduled backups (run ONCE in the Supabase SQL Editor).
--
-- Why: backend deploys wipe the container filesystem, so a snapshot that lives
-- inside the container is not a backup. The backend now pushes a snapshot of
-- the whole database to this table on a timer (BACKUP_INTERVAL_MINUTES, default
-- hourly), keeps the newest BACKUP_KEEP (default 7), and can restore one back
-- by id — so recovery no longer depends on an admin remembering to download a
-- file before the container went away.
--
-- Wired to the backend automatically. Running this SQL IS the whole setup:
-- backup-remote.js derives its sink from the Supabase driver config the app
-- already has, so there is no env var to add and no secret to paste.
--
--   SUPABASE_URL + SUPABASE_KEY  (already set on inventrak-api)
--       -> https://<ref>.supabase.co/rest/v1 + service_role key
--
-- Optional overrides (rare — only to point snapshots at a DIFFERENT project
-- than the data):
--   BACKUP_REMOTE_URL   = https://<other-ref>.supabase.co/rest/v1
--   BACKUP_REMOTE_KEY   = that project's service_role secret
--   BACKUP_REMOTE_TABLE = backup_snapshots (optional — this is the default)
--   BACKUP_INTERVAL_MINUTES = 0 turns the schedule off (default 60)
--   BACKUP_KEEP         = snapshots retained (default 7)
--   BACKUP_MAX_BYTES    = largest single snapshot pushed (default 4 MB)
--
-- Check status without a dashboard:
--   GET /api/meta            -> .backup      (scheduled: on/off, table, last push)
--   GET /api/admin/backups   -> the snapshots on hand (admin)
--   POST /api/admin/backup   -> take one now (admin) — proves the setup works
--                               without waiting a full interval
--
-- If the table does not exist, everything else still works: pushes fail with
-- the durable store's own message (throttled to one warning every 5 minutes)
-- and the console shows the reason instead of an empty success.
--
-- Storage shape: one row per snapshot. The full envelope (format, version,
-- driver, created_at, generated_by, counts, tables) lives in the jsonb "data"
-- column exactly as the download/upload format defines it, so a snapshot taken
-- here restores through the same code path as an uploaded file. driver /
-- created_at / bytes / counts are promoted to real columns so the console can
-- list what is available without downloading every body. Snapshot size is the
-- one real constraint: BACKUP_MAX_BYTES refuses anything too large to store as
-- a single row (Firestore's hard 1 MiB document limit is the reason the default
-- is not larger).

create table if not exists backup_snapshots (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  driver text,
  bytes integer not null default 0,
  counts jsonb not null default '{}'::jsonb,
  data jsonb not null
);

-- Listing (newest first) and the retention sweep both order by created_at, and
-- the sweep deletes from the far end of that order.
create index if not exists backup_snapshots_created_at_idx on backup_snapshots (created_at desc);

-- Row-level security: the backend writes with the service_role key (which
-- bypasses RLS), so no policies are added — anon/authenticated keys get
-- nothing. A snapshot contains password hashes, so keeping it out of reach of
-- the anon key is the point.

